def piecewise(value, points):
    """分段线性打分。points=[(x, score)...] 升序。首尾夹紧。缺失返回 None。"""
    if value is None:
        return None
    if value <= points[0][0]:
        return points[0][1]
    for i in range(len(points) - 1):
        x0, s0 = points[i]
        x1, s1 = points[i + 1]
        if x0 <= value <= x1:
            if x1 == x0:
                return s0
            return s0 + (s1 - s0) * (value - x0) / (x1 - x0)
    return points[-1][1]


def safe_div(a, b):
    if a is None or b in (None, 0):
        return None
    return a / b


def mean(vals):
    vals = [v for v in vals if v is not None]
    return sum(vals) / len(vals) if vals else None


def cagr(start, end, years):
    """复合增长率。start/end 为起始/结束值，years 为年数（必须为日历跨度）。

    起点**为负**时一律返回 None：负数基数上的「增长率」没有经济含义。
    只拦异号（ratio<0）是不够的——start=-100、end=-50 时 ratio=0.5>0，
    会被算成 -50% 的「增长」，把「亏损收窄」读成「下滑一半」。
    """
    if start in (None, 0) or end is None or years <= 0:
        return None
    if start < 0:
        return None  # 负基数，增长率无经济含义（与异号一并归为「不适用」）
    ratio = end / start
    if ratio < 0:
        return None  # 起点为正、终点为负（或相反），无法计算 CAGR
    return ratio ** (1.0 / years) - 1.0


def cv(vals):
    """变异系数 = std / |mean|。"""
    vals = [v for v in vals if v is not None]
    if len(vals) < 2:
        return None
    m = sum(vals) / len(vals)
    if m == 0:
        return None
    var = sum((v - m) ** 2 for v in vals) / len(vals)
    return math.sqrt(var) / abs(m)


def percentile_rank(value, history):
    """value 在 history 中的分位（0~1，越低表示 value 越处于历史低位）。"""
    hist = [v for v in history if v is not None]
    if value is None or not hist:
        return None
    below = sum(1 for v in hist if v <= value)
    return below / len(hist)


def _pct(v):
    """百分数 -> 小数，仅用于比阈值，不影响展示的 raw。

    ROE、资产负债率、毛利率系列这些科目取回来就是百分数（11.79 表示
    11.79%），而 RULES_V1 里的率阈值一律是小数。漏了这一步该指标就会
    恒定满分或恒定零分——V1.1 修的正是这 4 处。
    """
    return None if v is None else v / 100.0


def normalize_component_score(score, max_score):
    """把任意量纲的分量折算成 0~100，供最终模板加权。

    模板权重是按百分比设计的（20% 权重必须能贡献满 20 分），所以进模板的
    每个分量都必须先落到 0~100。原先烟蒂模板直接拿 `_score_liability_safety`
    的 0~10 分去乘 0.20，那一档理论最高只贡献 2 分（V1.1 修）。

    ``score``/``max_score`` 有任一为 None 或 max_score 为 0 时返回 None——
    缺失必须一路保持 None 走出去，让 final_score 按有效权重重平衡，
    绝不能在归一化这一步把「缺失」悄悄变成 0 分。
    """
    if score is None or not max_score:
        return None
    return score / max_score * 100.0


