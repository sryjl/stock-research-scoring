def _annual_series(series, n=5):
    """取最近 n 个年度值。series 为按时间升序的 [(period, value)]。

    注意：**这个函数丢掉了报告期**，返回值只能按「列表相邻=年份相邻」使用。
    序列来自 engine._series，它会把 value 为 None 的年份整个丢掉，所以中间
    缺一年时列表会比真实年数短。凡是要用到「年数」的地方（CAGR、同比），
    必须改用 :func:`_annual_pairs` + :func:`_year_span`。
    """
    return [v for _, v in series[-n:]]


def _annual_pairs(series, n=5):
    """取最近 n 个年度 (报告期, 值) 对。逐期保留日历信息，供跨度计算。"""
    return [(p, v) for p, v in series[-n:]]


def _year_span(pairs):
    """一组年度报告期的日历跨度（年）。不足两点或报告期不可解析返回 None。

    这是 CAGR 的分母。不能用 ``len(pairs) - 1``：engine._series 会把缺失年
    整个丢掉，2021/2022/2024/2025 四点（缺 2023）的真实跨度是 4 年而非 3 年，
    用 3 年开方会把增速系统性放大。
    """
    if len(pairs) < 2:
        return None
    try:
        first = int(str(pairs[0][0])[:4])
        last = int(str(pairs[-1][0])[:4])
    except (TypeError, ValueError):
        return None
    span = last - first
    return span if span > 0 else None


def _yoy_positive_years(series, n=5):
    """同比为正的年份数。

    只在**相邻两个日历年度**之间比较。序列缺年时，前一个可用年与后一个
    可用年之间隔了不止一年，那不是「同比」而是跨年比较，不计入。
    """
    pairs = _annual_pairs(series, n)
    if len(pairs) < 2:
        return None
    pos = 0
    for (p_prev, v_prev), (p_cur, v_cur) in zip(pairs, pairs[1:]):
        if v_prev is None or v_cur is None:
            continue
        if not _is_next_year(p_prev, p_cur):
            continue
        if v_prev and v_cur > v_prev:
            pos += 1
    return pos


def _is_next_year(prev_period, cur_period):
    """cur_period 是否正好是 prev_period 的下一个日历年度。"""
    try:
        return int(str(cur_period)[:4]) == int(str(prev_period)[:4]) + 1
    except (TypeError, ValueError):
        return False


