    rev_cv = cv(_annual_series(m["revenue"], 5))
    prof_cv = cv(_annual_series(m["net_profit"], 5))
    sync = None
    if rev_cv is not None and rev_cv > 0 and prof_cv is not None:
        sync = prof_cv / rev_cv
    s_sync = piecewise(sync, [(0.5, 0), (1.0, 5), (2.0, 10), (3.0, 15)]) if sync is not None else None
    comps.append(("利润/营收波动比", sync, s_sync, 15))

