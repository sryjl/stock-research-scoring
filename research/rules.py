def determine_type(attr_scores, industry=""):
    """**兜底判型**：按 8 个属性分排出 primary/secondary 与置信度。

    2026-09-24 起本函数**不再决定评分模板**——模板由 Router 的唯一结果
    ``primary_model`` 决定（见 MODEL_TO_TEMPLATE / template_for）。它只剩两个用途：

    1. 落库的 ``system_type``（画像判型；界面不再拿它当「类型」与主模型并列展示）；
    2. Router 给不出专属主模型时（未路由 / 适配度不足落到通用价值 / 旧数据没有
       路由结果），由它兜底选出模板，那一支的 ``final["template_source"]`` 是
       ``'attr_fallback'``。

    周期行业 + 周期属性强（>=55）时优先判为周期型（避免把周期股的利润暴增
    误判成成长）——这条规则原样保留，兜底路径的分数因此与改动前逐位一致。
    """
    s = {k: (v["score"] if v else None) for k, v in attr_scores.items()}
    present = {k: v for k, v in s.items() if v is not None}
    if not present:
        return {"primary": None, "secondary": None, "confidence": 0.0}
    is_cyc_industry = any(k in (industry or "") for k in RULES_V1["cyclical_industries"])
    cyc = present.get("cyclical")
    if is_cyc_industry and cyc is not None and cyc >= 55:
        others = {k: v for k, v in present.items() if k != "cyclical"}
        secondary = max(others, key=others.get) if others else None
        return {"primary": "cyclical", "secondary": secondary,
                "confidence": round(min(1.0, 0.5 + cyc / 100.0), 3)}
    ranked = sorted(present.items(), key=lambda kv: -kv[1])
    primary = ranked[0][0]
    secondary = ranked[1][0] if len(ranked) > 1 else None
    top2 = ranked[:2]
    spread = top2[0][1] - top2[1][1] if len(top2) > 1 else 30
    confidence = min(1.0, 0.4 + spread / 60.0)
    return {"primary": primary, "secondary": secondary, "confidence": round(confidence, 3)}


# 属性名 -> 模板名。**只用于兜底**：Router 给不出专属主模型时，由画像判型选模板。
_ATTR_TO_TEMPLATE = {
    "growth": "成长型", "quality": "价值型", "value": "价值型", "dividend": "高股息型",
    "cigar_butt": "烟蒂/资产价值型", "asset_value": "烟蒂/资产价值型", "cyclical": "周期价值型",
    "turnaround": "价值型",
}

# 模型 -> 评分模板。这是 Router 与评分层之间**唯一**的桥：primary_model 通过它决定
# 用哪套权重，于是「界面显示的模板」与「算分用的模板」在结构上不可能不同。
# 键必须与 router.MODEL_REGISTRY 完全一致（tests/test_router.py 钉住键集）。
# 兜底模型 GENERAL_VALUE_V2 **故意不在这里**：它表示「没有专属模型适配」，此时退回
# 画像判型（_ATTR_TO_TEMPLATE），并如实标注 template_source='attr_fallback'。
# 质量复利 / 困境反转 用「价值型」：与它们原先的属性映射（quality→价值型、
# turnaround→价值型）一致，不新增模板、不新造一套没标定过的权重。
MODEL_TO_TEMPLATE = {
    "CYCLICAL_CORE_V2": "周期价值型",
    "VALUE_CIGAR_V2": "烟蒂/资产价值型",
    "DIVIDEND_VALUE_V2": "高股息型",
    "GROWTH_CORE_V2": "成长型",
    "QUALITY_COMPOUNDER_V2": "价值型",
    "TURNAROUND_V2": "价值型",
}

#: final["template_source"] 的两个取值：模板由主模型决定 / 由画像判型兜底
TEMPLATE_SOURCE_ROUTE = "route"
TEMPLATE_SOURCE_ATTR = "attr_fallback"


def template_for(route, attr_type):
    """选评分模板，返回 ``(模板名, 来源, 决定者)``。

    只有 Router 明确给出一个**专属**主模型时，模板才由它决定（来源 ``'route'``，
    决定者是那个模型 id）；未路由 / 适配度不足落到通用价值 / 旧数据没有路由结果，
    一律退回画像判型（来源 ``'attr_fallback'``、决定者 ``None``），界面据此如实标注。

    这里不需要另判 ``route_status``：``primary_model`` 只在 CLEAR / HYBRID 下才是
    真模型，其余状态一律是 FALLBACK_MODEL，而它不在 MODEL_TO_TEMPLATE 里，
    自然走兜底。
    """
    model = (route or {}).get("primary_model")
    tmpl = MODEL_TO_TEMPLATE.get(model)
    if tmpl is not None:
        return tmpl, TEMPLATE_SOURCE_ROUTE, model
    primary = (attr_type or {}).get("primary")
    return _ATTR_TO_TEMPLATE.get(primary, "价值型"), TEMPLATE_SOURCE_ATTR, None


# 模板分量的原始量纲。进模板前一律经 normalize_component_score 折成 0~100，
# 这样「权重 × 100」就是该分量的理论最大贡献。新增分量必须在这里登记，
# 否则 TestFinalTemplateComponents 会失败。
MODULE_SCORE_MAX = 100.0        # 8 个属性模块 + 周期位置：都是 _assemble 归一化后的 0~100
CASHFLOW_RATIO_MAX = 100.0      # _cashflow_component 的 piecewise 上限
SURVIVAL_MAX = 100.0            # 两个「存活」分量都是 0~100
LIABILITY_SAFETY_MAX = 10.0     # _score_liability_safety 的上限（0~10，不是百分比）


def template_components(attr_scores, cyclical_position, metrics):
    """构造最终模板需要的全部分量。

    返回 ``{key: (raw_score, raw_max, coverage, status)}``。只负责取数与标注
    量纲，不做加权——加权在 final_score 里统一走 normalize_component_score。
    raw_max 是「该分量自己的满分」，不是 100；折算成 0~100 是
    normalize_component_score 的事。

    ``coverage`` 是该分量输入数据的齐备度，默认 1.0。只有「按年数计分」的
    两个存活分量会低于 1（历史有缺口），final_score 拿它按比例折算有效权重，
    这样缺数据不会既不得分又不掉覆盖率。``status`` 同理只对那两个有意义，
    用来把「取不到数」和「历史不够长」分开（都返回 None，但状态不同）。
    """
    def module(key):
        block = attr_scores.get(key) or {}
        return block.get("score"), MODULE_SCORE_MAX, 1.0, "module"

    quality, quality_max, quality_cov, _ = module("quality")
    growth, growth_max, growth_cov, _ = module("growth")
    value, value_max, value_cov, _ = module("value")
    dividend, dividend_max, dividend_cov, _ = module("dividend")
    cigar, cigar_max, cigar_cov, _ = module("cigar_butt")
    asset, asset_max, asset_cov, _ = module("asset_value")

    # 资产负债表分量：优先用资产价值模块，缺则退回烟蒂模块
    balance = ((asset, asset_max, asset_cov, "module") if asset is not None
               else (cigar, cigar_max, cigar_cov, "module"))
    cyc_pos = ((cyclical_position.get("score") if cyclical_position else None),
               MODULE_SCORE_MAX, 1.0, "module")
    cs_score, cs_status, cs_cov = _cashflow_survival(metrics)
    ps_score, ps_status, ps_cov = _profit_survival(metrics)

    return {
        "quality": (quality, quality_max, quality_cov, "module"),
        "growth": (growth, growth_max, growth_cov, "module"),
        "valuation": (value, value_max, value_cov, "module"),
        "cyclical_position": cyc_pos,
        "balance": balance,
        "cashflow": (_cashflow_component(metrics), CASHFLOW_RATIO_MAX, 1.0, "module"),
        "shareholder": (dividend, dividend_max, dividend_cov, "module"),
        "asset_value": (asset, asset_max, asset_cov, "module"),
        "valuation_discount": (value, value_max, value_cov, "module"),
        "liability_safety": (_liability_component(metrics), LIABILITY_SAFETY_MAX, 1.0, "module"),
        "cashflow_survival": (cs_score, SURVIVAL_MAX, cs_cov, cs_status),
        "profit_survival": (ps_score, SURVIVAL_MAX, ps_cov, ps_status),
        "dividend_quality": (dividend, dividend_max, dividend_cov, "module"),
    }


def final_score(attr_scores, cyclical_position, metrics, stock_type, route=None):
    """选模板并计算总分（0~100）。

    **模板由 Router 的唯一结果 ``primary_model`` 决定**（``route`` 参数，见
    template_for）；``stock_type`` 是 determine_type 的兜底判型，只在没路由时
    决定模板，并原样回传成 ``final["type"]``（= 落库的 system_type），
    让「画像判型」可被断言。

    传 ``route=None`` 表示这只股票没有路由结果（旧数据 / 未路由），此时行为与
    「模板跟随 primary_model」之前**逐位一致**。本函数**从不自己调 determine_type**。

    历史上这里漏传 industry，导致界面显示的类型（带行业）和算总分用的模板
    （不带行业）可以是两个东西，牧原就因此显示「周期型」却按「价值型」算分；
    现在这一类分叉在结构上不可能再出现——显示与算分读的是同一个 primary_model。
    """
    tmpl_name, source, decider = template_for(route, stock_type)
    tmpl = RULES_V1["templates"][tmpl_name]

    components = template_components(attr_scores, cyclical_position, metrics)

    weighted = 0.0
    wsum = 0.0
    detail = []
    for key, w in tmpl.items():
        raw, raw_max, cover, status = components.get(key, (None, None, 0.0, "missing_data"))
        # 缺失一路保持 None 走出去，绝不在这里变 0 分
        v = normalize_component_score(raw, raw_max)
        if v is None:
            detail.append({"key": key, "weight": w, "score": None, "missing": True,
                           "raw": raw, "raw_max": raw_max, "coverage": cover,
                           "status": status})
            continue
        # 数据有缺口的分量按 coverage 折算有效权重：既拿到分，覆盖率也如实下降。
        # 完整分量 cover == 1.0，所以这里对满分不变式（权重×100）没有影响。
        eff_w = w * cover
        weighted += v * eff_w
        wsum += eff_w
        detail.append({"key": key, "weight": eff_w, "template_weight": w,
                       "score": v, "missing": False, "raw": raw, "raw_max": raw_max,
                       "coverage": cover, "status": status})

    # type 一并回传，让「兜底判型」可被断言；模板的决定者另记两笔，
    # 界面据此如实标注「是主模型定的，还是未路由时按画像兜底的」。
    base = {"type": (stock_type or {}).get("primary"),
            "template": tmpl_name, "template_source": source, "template_model": decider,
            "components": detail}
    if wsum <= 0:
        return {**base, "score": None, "completeness": 0.0}

    score = weighted / wsum  # 有效权重重平衡
    completeness = wsum / sum(tmpl.values())
    return {**base, "score": round(score, 2), "completeness": round(completeness, 4)}


def _cashflow_component(metrics):
    ocf = sum(v for v in _annual_series(metrics.get("operating_cashflow", []), 5) if v is not None)
    np_ = sum(v for v in _annual_series(metrics.get("net_profit", []), 5) if v is not None)
    r = safe_div(ocf, np_)
    if r is None:
        return None
    return piecewise(r, [(0.5, 0), (0.7, 30), (0.9, 60), (1.1, 100)])


def _liability_component(metrics):
    return _score_liability_safety(metrics)


# 「近 N 年为正的年数」-> 得分。年数是绝对计数，不是比例：只活 4 年的公司
# 拿不到「5 年全正」的满分，这是刻意的保守口径。
CASHFLOW_SURVIVAL_SCALE = {3: 100, 2: 60, 1: 30, 0: 0}
PROFIT_SURVIVAL_SCALE = {5: 100, 4: 80, 3: 50, 2: 25, 1: 10, 0: 0}


def _survival_score(m, key, window, scale):
    """近 window 年「为正年数」打分。返回 ``(score, status, coverage)``。

    engine._series 会把取不到值的年度直接丢掉，所以「这家公司历史本来就短」
    和「历史够长但科目有缺口」在数值序列上长得一模一样——只看序列长度会把
    两者混为一谈。``m["annual"]`` 保留的是完整报告期行数，用它才能分开，
    这也是本函数要收整个 m 而不只是收一条序列的原因。

      ok                   —— 报告期够长、科目齐备，按 window 年计分
      partial              —— 报告期够长但有缺口，按有效年数计分并压低 coverage
      insufficient_history —— 完整年度不足 window，不计分（不进分母）
      missing_data         —— 一个有效值都没有，不计分（不进分母）

    注意「有有效历史但 0 年为正」返回的是 0 而不是 None：那是真实结论，
    要占分母、贡献 0 分，不能和「取不到数」混同。
    """
    series = m.get(key, [])
    vals = _annual_series(series, window)
    present = [v for v in vals if v is not None]
    if not present:
        return None, "missing_data", 0.0
    # 报告期行数取不到时退回序列长度，至少不会把「有数据」误判成「历史不足」
    history = len(m.get("annual") or []) or len(series)
    if history < window:
        return None, "insufficient_history", 0.0
    score = scale.get(sum(1 for v in present if v > 0), 0)
    if len(present) >= window:
        return score, "ok", 1.0
    return score, "partial", len(present) / window


def _cashflow_survival(metrics):
    return _survival_score(metrics, "operating_cashflow", 3, CASHFLOW_SURVIVAL_SCALE)


def _profit_survival(metrics):
    return _survival_score(metrics, "net_profit", 5, PROFIT_SURVIVAL_SCALE)


def score_modules(m):
    """评分**前半段**：8 个属性模块 + 周期位置 + 风险 + 资产模型 + 两个规范指标。

    这里**不含类型判定，也不出总分**——顺序是定死的：属性分先有，Router 才能定
    主模型；主模型定了，才轮到 :func:`finalize` 选模板算总分。拆出来就是为了让
    engine 能把 Router 插在中间（见 ``engine._run_analysis``）。
    """
    attrs = {
        "growth": score_growth(m, m),
        "quality": score_quality(m, m),
        "value": score_value(m, m),
        "dividend": score_dividend(m, m),
        "cigar_butt": score_cigar_butt(m, m),
        "asset_value": score_asset_value(m, m),
        "cyclical": score_cyclical(m, m),
        "turnaround": score_turnaround(m, m),
    }
    cyc_pos = score_cyclical_position(m, m)
    risk = detect_risk(m)

    # 规范指标（canonical）：CFO/净利润 的 1 年与 3 年累计各自具名，落进
    # cur（= 落库的 valuation_metrics），前端与评分层共用同一个值。
    # 旧前端在现金流页按**单年**现算并和评分层的**3 年累计**共用一个裸名字，
    # 同名不同义；现在两个窗口都必须带 (1Y) / (3Y累计) 后缀。
    _ratios = cfo_netprofit_ratios(m)
    if isinstance(m.get("current"), dict):
        m["current"]["cfo_net_profit_1y"] = _ratios[1]["ratio"]
        m["current"]["cfo_net_profit_3y"] = _ratios[3]["ratio"]
    # 资产价值模型走资产语义层（附注级经济分类），不再是一级科目 × 固定折价率
    return {
        "rule_version": RULE_VERSION,
        "attributes": attrs,
        "cyclical_position": cyc_pos,
        "risk": risk,
        "asset_model": _assets(m).display_model(),
    }


def finalize(scored, m, route):
    """评分**后半段**：兜底判型 + 按唯一主模型选模板算总分。

    ``route`` 是 Router 的唯一结果（engine._run_analysis 里算的那一次）。
    生产路径**必须**传它；``route=None`` 只用于「这只股票没有路由结果」的兜底，
    此时模板退回画像判型，与改动前逐位一致。
    """
    typ = determine_type(scored["attributes"], m.get("industry", ""))
    fin_score = final_score(scored["attributes"], scored["cyclical_position"],
                            m, typ, route)
    return {**scored, "type": typ, "final": fin_score}


def analyze(m, route=None):
    """完整评分编排。m 为规整后的 metrics，返回结果 dict。

    生产路径见 ``engine._run_analysis``：它把 Router 插在 score_modules 与
    finalize 之间，模板因此跟随 ``primary_model``。直接调本函数（``route=None``）
    等于「这只股票没有路由结果」，模板退回画像判型。

    类型判定仍然**只做一次**，且只在 finalize 里做：``typ`` 同时喂给模板选择、
    界面展示、快照与研究库落库。下游任何模块都不得再自己调一次 determine_type。
    """
    return finalize(score_modules(m), m, route)
