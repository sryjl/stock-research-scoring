def _driver(*pairs):
    """按优先级挑第一个有值的驱动项，连它的单位一起返回。

    复合指标（财务安全 / 负债安全）没有单一原始值，细则里展示最能代表
    它的那个输入；输入缺失时按优先级顺延，单位跟着一起换。
    """
    for value, unit in pairs:
        if value is not None:
            return value, unit
    return None, None


def _annual_rows(m):
    """m 里的统一历史财务序列（年度升序）。没有则空列表。"""
    return m.get("annual") or []


def _annual_last(m, key):
    """最新一个有值的年度科目。全无数据返回 None。"""
    for entry in reversed(_annual_rows(m)):
        if entry.get(key) is not None:
            return entry[key]
    return None


def cfo_netprofit_ratios(m):
    """统一口径的 CFO ÷ 归母净利润：1 年、3 年累计、5 年累计。

    「现金流匹配」与「CFO/净利润」共用本函数的结果，不再各自取数。
    返回 ``{年数: {...}}``，每项含 ratio / numerator / denominator / years /
    status / reason。状态刻意分三档，不把「算不出来」和「不适用」混为一谈：

      ok                   —— 可计算
      not_applicable       —— 累计归母净利润 <= 0，比值无数学意义（亏损公司常态）
      insufficient_history —— 完整年度不够，才是真的取不到数
    """
    rows = _annual_rows(m)
    out = {}
    for n in CFO_RATIO_YEARS:
        window = fin_series.complete_window(rows, ("operating_cashflow", "net_profit"), n)
        if window is None:
            have = len(fin_series.last_n(rows, n))
            out[n] = {"ratio": None, "numerator": None, "denominator": None, "years": have,
                      "status": "insufficient_history",
                      "reason": f"完整年度不足 {n} 年（实际 {have} 年）"}
            continue
        num = sum(e["operating_cashflow"] for e in window)
        den = sum(e["net_profit"] for e in window)
        if den <= 0:
            out[n] = {"ratio": None, "numerator": num, "denominator": den, "years": n,
                      "status": "not_applicable",
                      "reason": f"{n}年累计归母净利润 {den:.4g} <= 0，CFO/净利润（3年累计）无意义"}
            continue
        out[n] = {"ratio": num / den, "numerator": num, "denominator": den, "years": n,
                  "status": "ok", "reason": None}
    return out


def _ratio_comp(name, ratios, mx, points):
    """按统一口径拼一个「CFO 类比值」评分项。"""
    n = CFO_RATIO_SCORE_YEARS
    info = ratios[n]
    ratio = info["ratio"]
    score = piecewise(ratio, points) if ratio is not None else None
    extra = {
        # 数据齐备度：能判定「不适用」说明数据本身是全的
        "coverage": 1.0 if info["status"] in ("ok", "not_applicable")
                    else round(info["years"] / n, 4),
        "score_years": n,
        "ratios": {f"{k}Y": ratios[k]["ratio"] for k in CFO_RATIO_YEARS},
        "denominator": {f"{k}Y": ratios[k]["denominator"] for k in CFO_RATIO_YEARS},
    }
    return (name, ratio, score, mx, info["status"], info["reason"], extra)


