def detect_risk(m):
    flags = []
    level = "GREEN"
    cur = m["current"]
    bal = m["balance"]
    key = detect_industry_key(m.get("industry", ""))
    cfg = RISK_RULES.get(key, RISK_RULES["general"])

    # ---- 应收账款风险：比例 + 趋势 + 持续时间 ----
    ar_hist = m.get("receivable_growth_history", [])
    rev_hist = m.get("revenue_growth_history", [])
    ar_level = _growth_risk(ar_hist, rev_hist, cfg, "应收账款",
                             lambda a, b: f"应收同比 {a:+.1f}% vs 营收 {b:+.1f}%，差值 {a-b:+.1f}pct")
    if ar_level:
        flags.append(ar_level)
        level = _raise(level, ar_level["level"])

    # ---- 存货风险（行业差异化）----
    if cfg["inventory"]:
        inv_hist = m.get("inventory_growth_history", [])
        inv_level = _growth_risk(inv_hist, rev_hist, cfg, "存货",
                                 lambda a, b: f"存货同比 {a:+.1f}% vs 营收 {b:+.1f}%，差值 {a-b:+.1f}pct")
        if inv_level:
            flags.append(inv_level)
            level = _raise(level, inv_level["level"])

    # ---- 商誉风险 ----
    gw_ratio = safe_div(bal.get("goodwill"), bal.get("total_equity"))
    if gw_ratio is not None:
        if gw_ratio > 0.30:
            flags.append({"type": "商誉", "detail": f"商誉/净资产 {gw_ratio*100:.0f}%（超30%）", "level": "RED候选"})
            level = _raise(level, "ORANGE")
        elif gw_ratio > 0.20:
            flags.append({"type": "商誉", "detail": f"商誉/净资产 {gw_ratio*100:.0f}%", "level": "ORANGE"})
            level = _raise(level, "ORANGE")
        elif gw_ratio > 0.10:
            flags.append({"type": "商誉", "detail": f"商誉/净资产 {gw_ratio*100:.0f}%", "level": "YELLOW"})
            level = _raise(level, "YELLOW")

    # ---- 现金流风险 ----
    ocf = sum(_annual_series(m["operating_cashflow"], 3))
    np_ = sum(_annual_series(m["net_profit"], 3))
    cf_ratio = safe_div(ocf, np_)
    if cf_ratio is not None and np_ is not None and np_ != 0:
        if cf_ratio < 0:
            flags.append({"type": "现金流", "detail": f"CFO/净利润（3年累计） {cf_ratio:.2f}（为负）", "level": "RED候选"})
            level = _raise(level, "ORANGE")
        elif cf_ratio < 0.5:
            flags.append({"type": "现金流", "detail": f"CFO/净利润（3年累计） {cf_ratio:.2f}", "level": "ORANGE"})
            level = _raise(level, "ORANGE")
        elif cf_ratio < 0.8:
            flags.append({"type": "现金流", "detail": f"CFO/净利润（3年累计） {cf_ratio:.2f}", "level": "YELLOW"})
            level = _raise(level, "YELLOW")

    # ---- 债务风险（类现金 / 全部有息负债，走资产语义层）----
    cover = _asset_val(m, "interest_debt_cover")
    if cover is not None:
        if cover < 0.5:
            flags.append({"type": "短债", "detail": f"类现金资产/有息负债 {cover:.2f}（<0.5）", "level": "RED候选"})
            level = _raise(level, "ORANGE")
        elif cover < 1.0:
            flags.append({"type": "短债", "detail": f"类现金资产/有息负债 {cover:.2f}", "level": "ORANGE"})
            level = _raise(level, "ORANGE")
        elif cover < 2.0:
            flags.append({"type": "短债", "detail": f"现金类资产/短债 {cover:.2f}", "level": "YELLOW"})
            level = _raise(level, "YELLOW")

    # ---- 连续亏损 ----
    profits = _annual_series(m["net_profit"], 4)
    losses = sum(1 for v in profits if v is not None and v < 0)
    if losses >= 3:
        flags.append({"type": "连续亏损", "detail": f"近4年 {losses} 年亏损", "level": "RED候选"})
        level = _raise(level, "ORANGE")
    elif losses >= 2:
        flags.append({"type": "连续亏损", "detail": f"近4年 {losses} 年亏损", "level": "ORANGE"})
        level = _raise(level, "ORANGE")

    return {"level": level, "flags": flags, "signal": risk_signal_label(level)}


def _growth_risk(hist_a, hist_b, cfg, typ, fmt):
    """增长类风险：连续 N 期差值超阈值才升级，单期异常只作 YELLOW 候选。"""
    n = min(len(hist_a), len(hist_b), 3)
    gaps = []
    for i in range(n):
        a, b = hist_a[i][1], hist_b[i][1]
        if a is not None and b is not None:
            gaps.append(a - b)
    if not gaps:
        return None
    consecutive = 0
    for g in gaps:
        if g > cfg["gap_yellow"]:
            consecutive += 1
        else:
            break
    if consecutive == 0:
        return None
    latest_gap = gaps[0]
    # 连续 >=3 期，或连续 >=2 期且差值超过 orange 阈值 -> ORANGE；单期 -> YELLOW 候选
    if consecutive >= 3 or (consecutive >= 2 and latest_gap > cfg["gap_orange"]):
        lv = "ORANGE"
    else:
        lv = "YELLOW"
    a0, b0 = hist_a[0][1], hist_b[0][1]
    return {"type": typ, "level": lv,
            "detail": fmt(a0, b0) + f"（连续 {consecutive} 期）",
            "duration": consecutive, "gap": latest_gap, "a": a0, "b": b0}


def _raise(cur, new):
    order = {"GREEN": 0, "YELLOW": 1, "ORANGE": 2, "RED": 3}
    return new if order[new] > order[cur] else cur


