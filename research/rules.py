def _score_liability_safety(m):
    """类现金覆盖有息负债 + 净现金/市值 -> 0~10。全缺失返回 None。"""
    a = _assets(m)
    if not a.available:
        return None
    st = a.interest_debt_cover
    ncr = a.net_cash_to_market_cap
    if a.debt_free:
        st = None   # 无定义，但下面按「无债务」直接记满分项
    if st is None and ncr is None and not a.debt_free:
        return None
    pts = 5
    if a.debt_free:
        pts += 5
    elif st is not None:
        if st >= 2:
            pts += 5
        elif st >= 1:
            pts += 3
    if ncr is not None and ncr > 0.3:
        pts += 2
    return min(pts, 10)


def score_cyclical(m, fin):
    cfg = RULES_V1["cyclical"]
    comps = []
    profits = _annual_series(m["net_profit"], 8)
    c = cv(profits)
    s_cv = piecewise(c, cfg["profit_cv"]) if c is not None else None
