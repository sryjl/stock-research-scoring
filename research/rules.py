def score_dividend(m, fin):
    cfg = RULES_V1["dividend"]
    comps = []
    cur = m["current"]
    divs = m["dividends"]

    dy = cur.get("dividend_yield")
    comps.append(("股息率", dy, piecewise(dy, cfg["yield"]) if dy is not None else None, 30))

    # 连续分红年份：divs=None 表示数据缺失；[] 表示确认无分红
    if divs is None:
        comps.append(("连续分红年数", None, None, 20, "missing_data", "无分红数据"))
    else:
        yrs = min(len(set(d.get("year") for d in divs if d.get("year"))), 5)
        comps.append(("连续分红年数", yrs, cfg["consecutive_years"].get(yrs), 20))

    # 分红现金覆盖 = 最近 3 个完整年度累计 FCF ÷ 同期累计现金分红。
    # FCF 复用统一历史序列（= 经营现金流 - 资本开支），分红按所属财报年度
    # 对齐到同一个 3 年窗口，两边口径一致才可比。
    annual = _annual_rows(m)
    fcf_window = fin_series.complete_window(annual, ("free_cashflow",), 3)
    fcf3 = sum(e["free_cashflow"] for e in fcf_window) if fcf_window else None
    window_years = {e["report_period"][:4] for e in fcf_window} if fcf_window else set()
    window_divs = [d for d in (divs or [])
                   if (d.get("report_date") or "")[:4] in window_years]
    known_amounts = [d["amount"] for d in window_divs if d.get("amount") is not None]
    if divs is None:
        comps.append(("分红现金覆盖", None, None, 20, "missing_data", "无分红数据"))
    elif not divs:
        # 确认无分红 → 真实 0 分
        comps.append(("分红现金覆盖", 0, 0, 20, "ok", "确认无分红"))
    elif not fcf_window:
        comps.append(("分红现金覆盖", None, None, 20, "missing_data",
                      "最近 3 个完整年度自由现金流数据不足",
                      {"coverage": round(len(fin_series.last_n(annual, 3)) / 3, 4)}))
    elif not window_divs:
        # 窗口内确实没有分红记录 → 真实 0 分
        comps.append(("分红现金覆盖", 0, 0, 20, "ok", f"{min(window_years)}~{max(window_years)} 无分红",
                      {"coverage": 1.0, "fcf_3y": fcf3, "window": sorted(window_years)}))
    elif not known_amounts:
        # 有分红记录但拿不到金额（缺股本/派息）→ 缺失，不得按「无分红」记 0 分
        comps.append(("分红现金覆盖", None, None, 20, "missing_data", "同期分红金额缺失（缺股本或派息字段）"))
    else:
        div_amt = sum(known_amounts)
        cover = fcf3 / div_amt if div_amt > 0 else None
        if cover is None:
            # 账面上有分红记录但金额合计为 0 → 当作确认无分红
            comps.append(("分红现金覆盖", 0, 0, 20, "ok", "同期确认无现金分红"))
        else:
            comps.append(("分红现金覆盖", cover, piecewise(cover, cfg["fcf_cover"]), 20,
                          "ok", None,
                          {"coverage": 1.0, "fcf_3y": fcf3, "dividend_3y": div_amt,
                           "window": sorted(window_years)}))

    # 派息率合理性。亏损公司派息率没有意义，明确标为「不适用」而不是「缺失」；
    # 确认无分红的公司派息率是真实的 0。
    payout = cur.get("payout_ratio")
    last_np = _annual_last(m, "net_profit")
    if payout is not None:
        comps.append(("派息率", payout, _score_payout(payout), 15, "ok", None, {"coverage": 1.0}))
    elif last_np is not None and last_np <= 0:
        comps.append(("派息率", None, None, 15, "not_applicable",
                      f"最近年度归母净利润 {last_np:.4g} <= 0，派息率无意义"))
    elif divs == []:
        comps.append(("派息率", 0.0, _score_payout(0.0), 15, "ok", "确认无分红", {"coverage": 1.0}))
    else:
        comps.append(("派息率", None, None, 15, "missing_data", "缺少分红或归母净利润数据"))

    # 财务安全（净现金 + 负债率 + 现金流综合）。没有单一原始值，
    # 细则里展示权重最高的那个输入。
    safety = _score_financial_safety(m)
    am = _assets(m)
    ncr = am.net_cash_to_market_cap if am.available else None
    drv, drv_unit = _driver((ncr, RATIO),
                            (None if m["is_financial"] else cur.get("debt_asset_ratio"), POINTS))
    comps.append(("财务安全", drv, safety, 15,
                  "ok" if safety is not None else "missing_data",
                  None if safety is not None else _asset_missing_reason(m),
                  {"unit": drv_unit}))

    return _assemble(comps)


def _score_payout(payout):
    if payout is None:
        return None
    if 0.20 <= payout <= 0.60:
        return 15
    if 0.10 <= payout < 0.20 or 0.60 < payout <= 0.80:
        return 10
    if 0 <= payout < 0.10 or 0.80 < payout <= 1.0:
        return 5
    if payout > 1.0:
        return 0
    return 5


def _score_financial_safety(m):
    """净现金 + 资产负债率 + 经营现金流 -> 0~15。全缺失返回 None。

    净现金项走资产语义层；资产负债率和现金流与资产口径无关，照旧。
    """
    pts = 0
    any_data = False
    cur = m["current"]
    ncr = _asset_val(m, "net_cash_to_market_cap")
    if ncr is not None:
        any_data = True
        if ncr > 0.2:
            pts += 5
        elif ncr > 0:
            pts += 3
    if not m["is_financial"]:
        # 资产负债率是百分数，阈值是小数的 40% / 60%
        dr = _pct(cur.get("debt_asset_ratio"))
        if dr is not None:
            any_data = True
            if dr < 0.4:
                pts += 5
            elif dr < 0.6:
                pts += 3
    ocf = sum(_annual_series(m["operating_cashflow"], 3))
    if ocf is not None:
        any_data = True
        if ocf > 0:
            pts += 5
        elif ocf > -1e-9:
            pts += 3
    return min(pts, 15) if any_data else None


