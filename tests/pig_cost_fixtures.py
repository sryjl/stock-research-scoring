def meta_for(key):
    """夹具 → ``extract`` 认的 meta 字典（字段名与缓存 meta 对齐）。"""
    source = DOCUMENTS if key in DOCUMENTS else SYNTHETIC
    code, period, title, doc_key, publish_date, _page, _rows = source[key]
    return {"stock_code": code, "code": code, "report_period": period,
            "report_type": "A" if period.endswith("A") else "H1",
            "title": title, "publish_date": publish_date, "source_url": "",
            "_doc_key": doc_key, "_root": "fixture"}


def rows_for(*keys):
    """一个或多个夹具 → ``extract`` 认的行列表。

    跨夹具时按 ``(页, -y)`` 排序，与 ``_lines_of_page`` 的阅读顺序一致——
    行序不影响判定，但让夹具看起来就像报告的一页。
    """
    out = []
    for key in keys:
        source = DOCUMENTS if key in DOCUMENTS else SYNTHETIC
        _code, _period, _title, _doc_key, _date, page, rows = source[key]
        for y, text in rows:
            out.append({"page": page, "y": y, "cells": [{"x": 56.64, "text": text}]})
    out.sort(key=lambda row: (row["page"], -row["y"]))
    return out
