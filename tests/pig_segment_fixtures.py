def runs_for(*keys):
    """``runs_for("p144")`` → 一串 ``pdftext.Run``。多给几把 key 就合成一份多页的。"""
    out = []
    for key in keys:
        _code, _period, page, rows = PAGES[key]
        for x, y, text, size in rows:
            out.append(pdftext.Run(page, x, y, text, "F1", size))
    return out


